function run_benchmarks()
    %%

    benchmarks = { ...
        @test_update_qr, ...
        @test_forward_backward_solve, ...
        @test_multiplier_line_search, ...
        @test_get_condensed_adjoint, ...
        @test_get_condensed_gradient, ...
        @test_get_condensed_hessian, ...
        @test_get_condensed_primal_feasibility, ...
        @test_get_condensed_quadratic_contraints, ...
        @test_condensed_predictor_corrector, ...
        @test_condensed_rompc_step, ...
    };

    for i = 1: length(benchmarks)
        fprintf("run benchmark %d/%d (@%s) ...", i, length(benchmarks), char(benchmarks{i}));
        result = benchmarks{i}("benchmark");

        if result.passed == true
            fprintf(" passed\n");
            fprintf("    matlab: %g us, mex: %g us (%.0f %%)\n", ...
                result.t_ml * 1e6, result.t_mex * 1e6, result.t_ml / result.t_mex * 100);
        else
            fprintf(" FAILED\n");
        end
    end
end
